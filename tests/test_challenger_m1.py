class TestConcurrencyAndSeedIsolation:
    """Stress-tests multithreaded seed isolation and concurrent request integrity."""

    def test_multithreaded_seed_isolation_no_leakage(self):
        """
        Stress Test:
        Runs 20 threads simultaneously:
        - 10 threads use fixed seed=777 (must ALWAYS produce identical output).
        - 10 threads use seed=None (must produce varied outputs).
        Ensures thread-local seed isolation without polluting global random state.
        """
        seed_target = sample_random_scene(seed=777)
        target_sig = (
            seed_target["style"],
            seed_target["location"],
            seed_target["lighting"],
            seed_target["palette"]
        )

        seeded_results = []
        unseeded_results = []
        lock = threading.Lock()

        def worker_seeded():
            for _ in range(20):
                res = sample_random_scene(seed=777)
                sig = (res["style"], res["location"], res["lighting"], res["palette"])
                with lock:
                    seeded_results.append(sig)

        def worker_unseeded():
            for _ in range(20):
                res = sample_random_scene(seed=None)
                sig = (res["style"], res["location"], res["lighting"], res["palette"])
                with lock:
                    unseeded_results.append(sig)

        threads = []
        for _ in range(10):
            threads.append(threading.Thread(target=worker_seeded))
            threads.append(threading.Thread(target=worker_unseeded))

        for t in threads:
            t.start()
        for t in threads:
            t.join()

        # All 200 seeded calls MUST be identical to target_sig
        assert len(seeded_results) == 200
        assert all(s == target_sig for s in seeded_results), "Seeded execution suffered thread contamination!"

        # Unseeded calls MUST have high variety
        assert len(unseeded_results) == 200
        unique_unseeded = set(unseeded_results)
        assert len(unique_unseeded) > 50, f"Unseeded variety too low ({len(unique_unseeded)}/200 unique)"

    def test_concurrent_api_generate_requests_under_load(
        self,
        sample_jpeg_bytes: bytes,
        sample_png_bytes: bytes
    ):
        """
        High-load stress test:
        Sends 40 concurrent HTTP requests to POST /api/generate across 5 different modes.
        Verifies:
        - 100% 200 OK success rate.
        - Zero thread contention or cross-request state leakage.
        """
        with patch("google.genai.Client") as mock_client_cls:
            inst = MagicMock()

            def generate_mock(model, contents, config):
                # Simulate small I/O delay
                time.sleep(0.01)
                # Find mode from contents
                mode_str = "solo mueble"
                for c in contents:
                    if isinstance(c, str) and "MODE " in c:
                        mode_str = c.split(":")[0]
                resp = MagicMock()
                resp.text = make_dummy_art_director_json(model)
                return resp

            inst.models.generate_content.side_effect = generate_mock
            mock_client_cls.return_value = inst

            from app import app, ALLOWED_MODES
            test_client = TestClient(app)

            def send_request(req_id: int):
                target_mode = ALLOWED_MODES[req_id % len(ALLOWED_MODES)]
